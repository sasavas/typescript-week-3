/**
 * Arrow functions provide a concise syntax 
 * for writing function expressions in JavaScript,
 *  especially useful for callbacks and shorter functions.
 */

// ES5 function expression
// var add = function (a, b) {
//     return a + b;
// };

// ES6 arrow function
const add = (a, b) => a + b;

console.log(add(2, 3)); // Outputs: 5
